#!/usr/bin/env python3
"""Generate exact pinned Pkl/Java identifier predicate intervals, not Unicode XID."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

import oracle

ROOT = Path(__file__).resolve().parents[1]
PROBE = Path('tools/java/M2IdentifierProbe.java')
TARGET = Path('crates/pkl-runtime/src/parser/unicode_identifier.rs')


def intervals(payload):
    if not payload or not payload.endswith(b'\n'):
        raise ValueError('missing identifier inventory or terminal newline')
    result = {'start': [], 'part': []}
    for line in payload[:-1].split(b'\n'):
        match = re.fullmatch(rb'(start|part)\t([0-9a-f]+)\t([0-9a-f]+)', line)
        if not match:
            raise ValueError('invalid identifier interval transport')
        kind = match[1].decode()
        begin, end = [int(value, 16) for value in match.groups()[1:]]
        if not 0 <= begin <= end <= 0xffff or (result[kind] and begin <= result[kind][-1][1] + 1):
            raise ValueError('overlapping, nonmaximal or invalid Unicode intervals')
        result[kind].append((begin, end))
    if not all(result.values()):
        raise ValueError('identifier inventory incomplete')
    return result


def render(payload, metadata, probe_hash):
    ranges = intervals(payload)
    runtime = metadata['jdk']['properties']['java.runtime.version']
    vendor = metadata['jdk']['properties']['java.vendor']
    lines = ['// @generated by tools/m2_identifier_tables.py --write; do not edit.',
             '// Pkl 0.32.0 Lexer.java predicates consume UTF-16 code units; supplementary scalars are excluded.',
             f'// Oracle JDK: {vendor} {runtime}', f'// Probe SHA-256: {probe_hash}',
             f'// Raw interval SHA-256: {hashlib.sha256(payload).hexdigest()}', '']
    for kind in ('start', 'part'):
        lines.append(f'pub(super) const {kind.upper()}_RANGES: &[(u32, u32)] = &[')
        lines.extend(f'    (0x{begin:x}, 0x{end:x}),' for begin, end in ranges[kind])
        lines.extend(['];', ''])
    return '\n'.join(lines).encode()


def execute(output, write):
    metadata = oracle.ensure_oracle(ROOT)
    output.mkdir(parents=True, exist_ok=False)
    hashes = {str(path): oracle.sha256(ROOT / path) for path in [PROBE, Path('tools/m2_identifier_tables.py'),
            Path('tools/oracle.py'), Path('oracle.lock.json'), Path('references.lock'),
            Path('external/pkl/pkl-parser/src/main/java/org/pkl/parser/Lexer.java')]}
    for relative in hashes:
        destination = output / 'sources' / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((ROOT / relative).read_bytes())
    command = [*metadata['command'][:-1], str(ROOT / PROBE)]
    process = subprocess.run(command, cwd=ROOT, env=metadata['environment'], capture_output=True, timeout=120)
    (output / 'stdout.bin').write_bytes(process.stdout)
    (output / 'stderr.bin').write_bytes(process.stderr)
    (output / 'oracle.json').write_text(json.dumps(metadata, indent=2) + '\n')
    if process.returncode or process.stderr:
        raise ValueError('identifier Java probe failed; raw captures preserved')
    generated = render(process.stdout, metadata, hashes[str(PROBE)])
    (output / 'unicode_identifier.rs').write_bytes(generated)
    if write:
        (ROOT / TARGET).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / TARGET).write_bytes(generated)
    elif not (ROOT / TARGET).is_file() or (ROOT / TARGET).read_bytes() != generated:
        raise ValueError('identifier table stale; use --write after reviewing evidence')
    report = dict(scope='Full Unicode identifier start/part predicates, not full parser compatibility.',
            command=command, exit_code=process.returncode, oracle=metadata, sources=hashes,
            interval_counts={key: len(value) for key, value in intervals(process.stdout).items()},
            source_stability=all(oracle.sha256(ROOT / path) == expected for path, expected in hashes.items()))
    report['evidence_sha256'] = {str(path.relative_to(output)): oracle.sha256(path)
            for path in sorted(output.rglob('*')) if path.is_file()}
    (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    if not report['source_stability']:
        raise ValueError('identifier generator inputs changed during execution')
    print(json.dumps(report['interval_counts'], sort_keys=True))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='fresh evidence directory')
    parser.add_argument('--write', action='store_true', help='write the generated Rust table; otherwise verify exact current bytes')
    args = parser.parse_args()
    execute(args.output.resolve(), args.write)


if __name__ == '__main__':
    main()
