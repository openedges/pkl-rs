#!/usr/bin/env python3
"""Generate lossless ROOT-uppercase mappings from the exact reference JDK."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import time

import oracle

ROOT = Path(__file__).resolve().parents[1]
PROBE = Path('tools/java/M2UppercaseProbe.java')
TARGET = Path('crates/pkl-runtime/src/string_case/uppercase.rs')
TOTAL = 0x110000


def original_units(point):
    if point < 0x10000:
        return (point,)
    value = point - 0x10000
    return (0xd800 + (value >> 10), 0xdc00 + (value & 0x3ff))


def mappings(payload):
    if len(payload) < 12 or payload[:8] != b'PKLUPR1\0' or struct.unpack_from('>I', payload, 8)[0] != TOTAL:
        raise ValueError('incomplete uppercase code-point inventory')
    position = 12
    changed = []
    for point in range(TOTAL):
        if position + 2 > len(payload):
            raise ValueError('truncated uppercase length')
        length, = struct.unpack_from('>H', payload, position)
        position += 2
        if not 1 <= length <= 3 or position + length * 2 > len(payload):
            raise ValueError('invalid or truncated uppercase UTF-16 value')
        units = struct.unpack_from('>' + 'H' * length, payload, position)
        position += length * 2
        if 0xd800 <= point <= 0xdfff and units != (point,):
            raise ValueError('uppercase changed an unmatched surrogate')
        if units != original_units(point):
            changed.append((point, units))
    if position != len(payload):
        raise ValueError('unexpected trailing uppercase data')
    return changed


def render(payload, metadata, probe_hash):
    rows = mappings(payload)
    properties = metadata['jdk']['properties']
    lines = ['// @generated by tools/m2_uppercase_tables.py --write; do not edit.',
             '// Complete Java String.toUpperCase(Locale.ROOT) code-point mappings.',
             '// Unlisted code points, including unmatched surrogates, retain their UTF-16 units.',
             f"// Oracle JDK: {properties['java.vendor']} {properties['java.runtime.version']}",
             f'// Probe SHA-256: {probe_hash}',
             f'// Raw UTF-16 inventory SHA-256: {hashlib.sha256(payload).hexdigest()}', '',
             'pub(super) const UPPERCASE: &[(u32, &[u16])] = &[']
    lines.extend(f'    (0x{point:x}, &[' + ', '.join(f'0x{unit:x}' for unit in units) + ']),'
                 for point, units in rows)
    lines.extend(['];', ''])
    return '\n'.join(lines).encode()


def execute(output, write):
    metadata = oracle.ensure_oracle(ROOT)
    output.mkdir(parents=True, exist_ok=False)
    inputs = [PROBE, Path(__file__).relative_to(ROOT), Path('tools/oracle.py'),
              Path('oracle.lock.json'), Path('references.lock'),
              Path('external/pkl/pkl-core/src/main/java/org/pkl/core/stdlib/base/StringNodes.java')]
    hashes = {str(path): oracle.sha256(ROOT / path) for path in inputs}
    for relative in hashes:
        destination = output / 'sources' / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((ROOT / relative).read_bytes())
    for name in ['home', 'tmp']:
        (output / name).mkdir()
    environment = dict(metadata['environment'])
    environment.update(HOME=str(output / 'home'), TMPDIR=str(output / 'tmp'),
                       TMP=str(output / 'tmp'), TEMP=str(output / 'tmp'))
    command = [f'-Duser.home={output / "home"}' if arg.startswith('-Duser.home=')
               else f'-Djava.io.tmpdir={output / "tmp"}' if arg.startswith('-Djava.io.tmpdir=')
               else arg for arg in [*metadata['command'][:-1], str(ROOT / PROBE)]]
    report = dict(scope='Complete pinned Java ROOT-uppercase code-point inventory; not full language/API compatibility.',
                  command=command, cwd=str(ROOT), environment=environment, sources=hashes,
                  status='failed', timed_out=False)
    (output / 'oracle.json').write_text(json.dumps(metadata, indent=2) + '\n')
    started = time.monotonic()
    try:
        try:
            process = subprocess.run(command, cwd=ROOT, env=environment, capture_output=True, timeout=120)
            stdout, stderr = process.stdout, process.stderr
            report['exit_code'] = process.returncode
        except subprocess.TimeoutExpired as error:
            stdout, stderr = error.stdout or b'', error.stderr or b''
            report.update(exit_code=None, timed_out=True)
        (output / 'stdout.bin').write_bytes(stdout)
        (output / 'stderr.bin').write_bytes(stderr)
        report['elapsed_seconds'] = time.monotonic() - started
        if report['timed_out'] or report['exit_code'] != 0 or stderr:
            raise ValueError('uppercase Java probe failed; raw captures preserved')
        generated = render(stdout, metadata, hashes[str(PROBE)])
        (output / 'uppercase.rs').write_bytes(generated)
        if not all((ROOT / path).is_file() and oracle.sha256(ROOT / path) == digest
                   for path, digest in hashes.items()):
            raise ValueError('uppercase generator inputs changed during execution')
        if write:
            (ROOT / TARGET).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / TARGET).write_bytes(generated)
        elif not (ROOT / TARGET).is_file() or (ROOT / TARGET).read_bytes() != generated:
            raise ValueError('uppercase table stale; use --write after reviewing evidence')
        report.update(status='pass', code_points=TOTAL, changed_code_points=len(mappings(stdout)),
                      raw_sha256=hashlib.sha256(stdout).hexdigest(), table_sha256=hashlib.sha256(generated).hexdigest())
    finally:
        report['source_stability'] = all((ROOT / path).is_file() and oracle.sha256(ROOT / path) == digest
                                         for path, digest in hashes.items())
        if not report['source_stability']:
            report['status'] = 'failed'
        report['evidence_sha256'] = {str(path.relative_to(output)): oracle.sha256(path)
                                   for path in sorted(output.rglob('*')) if path.is_file()}
        (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    if not report['source_stability']:
        raise ValueError('uppercase generator inputs changed during execution')
    print(json.dumps({key: report[key] for key in ['status', 'code_points', 'changed_code_points', 'raw_sha256']}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='fresh evidence directory')
    parser.add_argument('--write', action='store_true', help='write generated table; otherwise compare exact current bytes')
    args = parser.parse_args()
    execute(args.output.resolve(), args.write)


if __name__ == '__main__':
    main()
