#!/usr/bin/env python3
"""Generate pinned Java UTF-16 Unicode escape character predicates and digits."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

import oracle

ROOT = Path(__file__).resolve().parents[1]
PROBE = Path('tools/java/M2UnicodeEscapeProbe.java')
TARGET = Path('crates/pkl-runtime/src/parser/unicode_escape.rs')
KINDS = ('letter_or_digit', 'hex_digit')


def intervals(payload):
    if not payload or not payload.endswith(b'\n'):
        raise ValueError('missing Unicode escape inventory or terminal newline')
    result = {kind: [] for kind in KINDS}
    previous_kind = 0
    for line in payload[:-1].split(b'\n'):
        match = re.fullmatch(rb'(letter_or_digit|hex_digit)\t([0-9a-f]+)\t([0-9a-f]+)(?:\t([0-9a-f]+))?', line)
        if not match:
            raise ValueError('invalid Unicode escape interval transport')
        kind = match[1].decode()
        if KINDS.index(kind) < previous_kind:
            raise ValueError('noncanonical interval kind order')
        previous_kind = KINDS.index(kind)
        begin, end = int(match[2], 16), int(match[3], 16)
        if not 0 <= begin <= end <= 0xffff or (begin <= 0xdfff and end >= 0xd800):
            raise ValueError('invalid UTF-16 predicate interval')
        if (kind == 'hex_digit') != (match[4] is not None):
            raise ValueError('missing or unexpected digit value')
        row = (begin, end) if kind == 'letter_or_digit' else (begin, end, int(match[4], 16))
        if kind == 'hex_digit' and not 0 <= row[2] <= row[2] + end - begin < 16:
            raise ValueError('digit interval exceeds radix')
        if result[kind]:
            previous = result[kind][-1]
            if begin <= previous[1]:
                raise ValueError('overlapping or unordered intervals')
            if begin == previous[1] + 1 and (kind == 'letter_or_digit'
                    or row[2] == previous[2] + begin - previous[0]):
                raise ValueError('nonmaximal intervals')
        result[kind].append(row)
    if not all(result.values()):
        raise ValueError('Unicode escape inventory incomplete')
    letters = {unit for begin, end in result['letter_or_digit'] for unit in range(begin, end + 1)}
    if any(unit not in letters for begin, end, _ in result['hex_digit'] for unit in range(begin, end + 1)):
        raise ValueError('hex digit absent from lexer letter-or-digit predicate')
    return result


def render(payload, metadata, probe_hash):
    ranges = intervals(payload)
    properties = metadata['jdk']['properties']
    lines = ['// @generated by tools/m2_unicode_escape_tables.py --write; do not edit.',
             '// Pkl 0.32.0 Unicode escapes use Java Character predicates on UTF-16 units.',
             f"// Oracle JDK: {properties['java.vendor']} {properties['java.runtime.version']}",
             f'// Probe SHA-256: {probe_hash}',
             f'// Raw interval SHA-256: {hashlib.sha256(payload).hexdigest()}', '']
    for kind in KINDS:
        shape = 'u32, u32' if kind == 'letter_or_digit' else 'u32, u32, u32'
        lines.append(f'pub(super) const {kind.upper()}_RANGES: &[({shape})] = &[')
        lines.extend('    (' + ', '.join(f'0x{value:x}' for value in row) + '),' for row in ranges[kind])
        lines.extend(['];', ''])
    return '\n'.join(lines).encode()


def execute(output, write):
    metadata = oracle.ensure_oracle(ROOT)
    output.mkdir(parents=True, exist_ok=False)
    inputs = [PROBE, Path(__file__).relative_to(ROOT), Path('tools/oracle.py'),
              Path('oracle.lock.json'), Path('references.lock'),
              Path('external/pkl/pkl-parser/src/main/java/org/pkl/parser/Lexer.java'),
              Path('external/pkl/pkl-parser/src/main/java/org/pkl/parser/ParserImpl.java')]
    hashes = {str(path): oracle.sha256(ROOT / path) for path in inputs}
    for relative in hashes:
        destination = output / 'sources' / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((ROOT / relative).read_bytes())
    command = [*metadata['command'][:-1], str(ROOT / PROBE)]
    report = dict(scope='Pinned Java UTF-16 Unicode escape predicates; not full parser compatibility.',
                  command=command, sources=hashes, status='failed', timed_out=False)
    (output / 'oracle.json').write_text(json.dumps(metadata, indent=2) + '\n')
    try:
        try:
            process = subprocess.run(command, cwd=ROOT, env=metadata['environment'], capture_output=True, timeout=120)
            stdout, stderr = process.stdout, process.stderr
            report['exit_code'] = process.returncode
        except subprocess.TimeoutExpired as error:
            stdout, stderr = error.stdout or b'', error.stderr or b''
            report.update(exit_code=None, timed_out=True)
        (output / 'stdout.bin').write_bytes(stdout)
        (output / 'stderr.bin').write_bytes(stderr)
        if report['timed_out'] or report['exit_code'] != 0 or stderr:
            raise ValueError('Unicode escape Java probe failed; raw captures preserved')
        generated = render(stdout, metadata, hashes[str(PROBE)])
        (output / TARGET.name).write_bytes(generated)
        if write:
            (ROOT / TARGET).write_bytes(generated)
        elif not (ROOT / TARGET).is_file() or (ROOT / TARGET).read_bytes() != generated:
            raise ValueError('Unicode escape table stale; use --write after reviewing evidence')
        report['interval_counts'] = {key: len(value) for key, value in intervals(stdout).items()}
        report['status'] = 'pass'
    except Exception as error:
        report['error'] = str(error)
        raise
    finally:
        report['source_stability'] = all(oracle.sha256(ROOT / path) == expected for path, expected in hashes.items())
        if not report['source_stability']:
            report['status'] = 'failed'
        report['evidence_sha256'] = {str(path.relative_to(output)): oracle.sha256(path)
                for path in sorted(output.rglob('*')) if path.is_file()}
        (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    if not report['source_stability']:
        raise ValueError('Unicode escape generator inputs changed during execution')
    print(json.dumps(report['interval_counts'], sort_keys=True))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='fresh evidence directory')
    parser.add_argument('--write', action='store_true', help='write the generated table; otherwise verify exact bytes')
    args = parser.parse_args()
    execute(args.output.resolve(), args.write)


if __name__ == '__main__':
    main()
