def coverage(root, expected):
    ancestors = {str(parent) for rel in expected for parent in safe(rel).parents if str(parent) != '.'}
    found = set()
    for current, dirs, names in os.walk(root, followlinks=False):
        for name in dirs:
            p = Path(current) / name
            check(str(p.relative_to(root)) in ancestors and stat.S_ISDIR(p.lstat().st_mode), 'undeclared directory rejected before descent')
        for name in names:
            p = Path(current) / name
            check(stat.S_ISREG(p.lstat().st_mode), 'regular declared payload')
            found.add(str(p.relative_to(root)))
    check(found == expected, 'exact actual fixture coverage')


def verify(root):
    manifest_bytes = regular(root, 'manifest.json')
    check(sha(manifest_bytes) == MANIFEST_PIN, 'literal fixture manifest pin')
    # A literal-pinned manifest may define traversal before expensive reconstruction;
    # unknown directories are rejected without descending into them.
    coverage(root, set(json.loads(manifest_bytes)['files']) | {'manifest.json'})
    files, bundle, metadata = construct(root)
    expected = {'schema': 1, 'files': {rel: {'sha256': sha(data), 'bytes': len(data)} for rel, data in files.items()}}
    check(json.loads(regular(root, 'manifest.json')) == expected, 'manifest exact reconstructed coverage')
    for rel, data in files.items():
        check(regular(root, rel) == data, 'reconstructed fixture/provider bytes')
    return {'files': len(files) + 1, 'javaApiCalls': 944, 'javaOrderedEvents': 10124, 'sessions': 140,
            'providerProfiles': len(metadata['profiles']), 'scopeLedger': bundle['scopeLedger'],
            'manifestSha256': sha(regular(root, 'manifest.json')), 'evaluations': 0}


def export(oracle_base, target):
    check(not target.exists(), 'fresh export directory')
    files, _, _ = construct(oracle_base, True)
    target.mkdir(parents=True)
    for rel, data in files.items():
        p = target / safe(rel); p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(data)
    (target / 'manifest.json').write_bytes(dump({'schema': 1, 'files': {
        rel: {'sha256': sha(data), 'bytes': len(data)} for rel, data in files.items()}}))
    return verify(target)


