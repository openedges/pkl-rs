def check(ok, message):
    if not ok:
        raise ValueError(message)


def safe(rel):
    p = Path(rel)
    check(isinstance(rel, str) and not p.is_absolute() and '..' not in p.parts
          and str(p) == rel and rel != '.', 'unsafe relative fixture path')
    return p


def regular(root, rel):
    check(stat.S_ISDIR(root.lstat().st_mode), 'regular fixture root')
    p = root
    for part in safe(rel).parts[:-1]:
        p /= part
        check(stat.S_ISDIR(p.lstat().st_mode), 'regular payload parent')
    p /= safe(rel).parts[-1]
    check(stat.S_ISREG(p.lstat().st_mode), 'regular payload leaf')
    return p.read_bytes()


def units(data):
    check(len(data) % 2 == 0, 'even UTF16BE payload')
    return [int.from_bytes(data[i:i + 2], 'big') for i in range(0, len(data), 2)]


def boolean(value):
    check(value in ['true', 'false'], 'authored bool')
    return value == 'true'


def counters(data):
    return dict((k, int(v)) for k, v in (line.split('=', 1) for line in data.decode().splitlines()))


