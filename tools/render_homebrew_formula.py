"""Render a deterministic Homebrew Formula (`Formula/pkl-rs.rb`) from SHA256SUMS.txt."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

TOOLS_DIR = Path(__file__).resolve().parent
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

import check_release_version

SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")

REQUIRED_TARGETS = (
    ("darwin-arm64", "pkl-darwin-arm64.tar.gz", "pkldoc-darwin-arm64.tar.gz"),
    ("darwin-x64", "pkl-darwin-x64.tar.gz", "pkldoc-darwin-x64.tar.gz"),
    ("linux-arm64-gnu", "pkl-linux-arm64-gnu.tar.gz", "pkldoc-linux-arm64-gnu.tar.gz"),
    ("linux-x64-gnu", "pkl-linux-x64-gnu.tar.gz", "pkldoc-linux-x64-gnu.tar.gz"),
)


def parse_checksums(text: str) -> dict[str, str]:
    """Parse `sha256sum` / `shasum -a 256` output into `{filename: sha256}`."""
    checksums: dict[str, str] = {}
    for line_no, raw_line in enumerate(text.splitlines(), start=1):
        line = raw_line.strip()
        if not line:
            continue
        parts = line.split(None, 1)
        if len(parts) != 2:
            raise ValueError(f"Malformed checksum line {line_no}: {raw_line!r}")
        digest, raw_name = parts[0].lower(), parts[1].strip()
        if raw_name.startswith("*"):
            raw_name = raw_name[1:]
        filename = Path(raw_name).name
        if not SHA256_RE.match(digest):
            raise ValueError(f"Invalid SHA-256 digest on line {line_no}: {digest!r}")
        if filename in checksums and checksums[filename] != digest:
            raise ValueError(f"Conflicting SHA-256 digests for {filename!r}")
        checksums[filename] = digest
    return checksums


def render_formula(
    *,
    version: str,
    tag: str,
    checksums: dict[str, str],
    repo: str = "openedges/pkl-rs",
) -> str:
    """Render `Formula/pkl-rs.rb` after validating version, tag, repo, and all 8 digests."""
    if not check_release_version.SEMVER_RE.match(version):
        raise ValueError(f"Invalid SemVer version: {version!r}")
    tag_version = check_release_version.normalize_tag(tag)
    if tag_version != version:
        raise ValueError(f"Release tag {tag!r} (version {tag_version}) does not match version {version!r}")
    normalized_tag = f"v{tag_version}"
    if not REPO_RE.match(repo):
        raise ValueError(f"Invalid GitHub owner/repo: {repo!r}")

    missing: list[str] = []
    for _, pkl_archive, pkldoc_archive in REQUIRED_TARGETS:
        for archive in (pkl_archive, pkldoc_archive):
            digest = checksums.get(archive)
            if not digest or not SHA256_RE.match(digest):
                missing.append(archive)
    if missing:
        raise ValueError(f"Missing or invalid SHA-256 checksum(s) for Homebrew targets: {', '.join(missing)}")

    base_url = f"https://github.com/{repo}/releases/download/{normalized_tag}"
    core_baseline = version.split("-", 1)[0]

    def target_block(pkl_archive: str, pkldoc_archive: str) -> str:
        return (
            f'      url "{base_url}/{pkl_archive}"\n'
            f'      sha256 "{checksums[pkl_archive]}"\n'
            "\n"
            '      resource "pkldoc" do\n'
            f'        url "{base_url}/{pkldoc_archive}"\n'
            f'        sha256 "{checksums[pkldoc_archive]}"\n'
            "      end"
        )

    darwin_arm64 = target_block("pkl-darwin-arm64.tar.gz", "pkldoc-darwin-arm64.tar.gz")
    darwin_x64 = target_block("pkl-darwin-x64.tar.gz", "pkldoc-darwin-x64.tar.gz")
    linux_arm64 = target_block("pkl-linux-arm64-gnu.tar.gz", "pkldoc-linux-arm64-gnu.tar.gz")
    linux_x64 = target_block("pkl-linux-x64-gnu.tar.gz", "pkldoc-linux-x64-gnu.tar.gz")

    return f'''# typed: false
# frozen_string_literal: true

# Generated by tools/render_homebrew_formula.py for pkl-rs {normalized_tag}.
class PklRs < Formula
  desc "Pure-Rust implementation of Apple Pkl {core_baseline} CLI and documentation generator"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "Apache-2.0"

  conflicts_with "pkl", because: "both install a `pkl` binary"

  on_macos do
    on_arm do
{darwin_arm64}
    end
    on_intel do
{darwin_x64}
    end
  end

  on_linux do
    on_arm do
{linux_arm64}
    end
    on_intel do
{linux_x64}
    end
  end

  def install
    bin.install "pkl"
    resource("pkldoc").stage do
      bin.install "pkldoc"
    end
    prefix.install "LICENSE", "NOTICE", "THIRD-PARTY-NOTICES.md"
    generate_completions_from_executable(bin/"pkl", "shell-completion", shells: [:bash, :zsh, :fish])
  end

  test do
    assert_match "pkl-rs {core_baseline}", shell_output("#{{bin}}/pkl --version")
    assert_match "pkldoc-rs {core_baseline}", shell_output("#{{bin}}/pkldoc --version")
    (testpath/"config.pkl").write("name = \\"pkl-rs\\"\\nport = 8080\\n")
    output = shell_output("#{{bin}}/pkl eval -f json #{{testpath}}/config.pkl")
    assert_match "\\"port\\": 8080", output
  end
end
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, help="Release SemVer (e.g. 0.32.0-rc.1)")
    parser.add_argument("--tag", required=True, help="Git release tag (e.g. v0.32.0-rc.1)")
    parser.add_argument("--checksums", type=Path, required=True, help="Path to SHA256SUMS.txt")
    parser.add_argument("--output", required=True, help="Output file path (or '-' for stdout)")
    parser.add_argument("--repo", default="openedges/pkl-rs", help="GitHub owner/repo hosting release archives")
    args = parser.parse_args(argv)

    try:
        checksums = parse_checksums(args.checksums.read_text(encoding="utf-8"))
        rendered = render_formula(
            version=args.version,
            tag=args.tag,
            checksums=checksums,
            repo=args.repo,
        )
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.output == "-":
        sys.stdout.write(rendered)
    else:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
